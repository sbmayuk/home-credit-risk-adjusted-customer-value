SELECT
    SK_ID_PREV,
    SK_ID_CURR,
    MONTHS_BALANCE,

    CAST(CNT_INSTALMENT AS INT64) AS CNT_INSTALMENT,
    CAST(CNT_INSTALMENT_FUTURE AS INT64) AS CNT_INSTALMENT_FUTURE,

 CASE
    WHEN NAME_CONTRACT_STATUS = 'XNA' THEN NULL
    ELSE NAME_CONTRACT_STATUS
    END AS NAME_CONTRACT_STATUS,

   SK_DPD,
SK_DPD_DEF,

CASE
    WHEN CNT_INSTALMENT IS NULL
      OR CNT_INSTALMENT_FUTURE IS NULL THEN NULL
    WHEN CNT_INSTALMENT_FUTURE > CNT_INSTALMENT THEN 1
    ELSE 0
END AS instalment_inconsistency_flag

FROM {{ source('homecredit_raw', 'pos_cash_balance') }}